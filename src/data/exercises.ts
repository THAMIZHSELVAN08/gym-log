/**
 * Groups exercises by primary muscle for the exercise picker.
 */
export function groupExercisesByMuscle(exerciseList: NewExercise[]): Record<string, NewExercise[]> {
  return exerciseList.reduce<Record<string, NewExercise[]>>((acc, ex) => {
    if (!acc[ex.primaryMuscle]) acc[ex.primaryMuscle] = [];
    acc[ex.primaryMuscle]!.push(ex);
    return acc;
  }, {});
}
